@app.post("/profile/password")
def change_password(request:Request,current_password:str=Form(...),new_password:str=Form(...),confirm_password:str=Form(...),csrf:str=Form("")):
    u=current_user(request)
    if not u: return redirect_login()
    if not check_csrf(request,csrf): return RedirectResponse("/profile?error=csrf",303)
    if len(new_password)<10 or new_password!=confirm_password: return RedirectResponse("/profile?error=password",303)
    with db() as c: row=c.execute(text("SELECT password_hash FROM users WHERE id=:id"),{"id":u["id"]}).mappings().first()
    if not row or not pwd.verify(current_password,row["password_hash"]): return RedirectResponse("/profile?error=current",303)
    with db() as c: c.execute(text("UPDATE users SET password_hash=:p WHERE id=:id"),{"p":pwd.hash(new_password),"id":u["id"]})
    log_action(request,"password_change","user",u["id"])
    return RedirectResponse("/profile?success=changed",303)


