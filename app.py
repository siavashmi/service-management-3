@app.post("/users")
def add_user(request:Request,username:str=Form(...),password:str=Form(...),role:str=Form("user"),csrf:str=Form("")):
    u=current_user(request)
    if not u or u["role"]!="admin": return RedirectResponse("/",303)
    if not check_csrf(request,csrf): return RedirectResponse("/users?error=csrf",303)
    if len(password)<10 or role not in ("user","admin"): return RedirectResponse("/users?error=invalid",303)
    try:
        with db() as c: c.execute(text("INSERT INTO users(username,password_hash,role) VALUES(:u,:p,:r)"),{"u":username.strip(),"p":pwd.hash(password),"r":role})
        log_action(request,"create","user",details=username.strip())
    except IntegrityError: return RedirectResponse("/users?error=exists",303)
    return RedirectResponse("/users",303)


