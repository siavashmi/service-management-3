def init_db():
    if DB_IS_SQLITE:
        user_id = "INTEGER PRIMARY KEY AUTOINCREMENT"
        record_id = "INTEGER PRIMARY KEY AUTOINCREMENT"
        audit_id = "INTEGER PRIMARY KEY AUTOINCREMENT"
    else:
        user_id = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        record_id = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        audit_id = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    with db() as c:
        c.execute(text(f"""CREATE TABLE IF NOT EXISTS users(
            id {user_id},
            username VARCHAR(100) UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            role VARCHAR(20) NOT NULL DEFAULT 'user',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""))
        c.execute(text(f"""CREATE TABLE IF NOT EXISTS records(
            id {record_id},
            province VARCHAR(100), type VARCHAR(100), source_ne VARCHAR(255), source_port VARCHAR(255),
            direction VARCHAR(50), dest_ne VARCHAR(255), dest_port VARCHAR(255), rate_type VARCHAR(100),
            rate_number VARCHAR(50), status VARCHAR(50), service VARCHAR(255),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""))
        c.execute(text(f"""CREATE TABLE IF NOT EXISTS audit_logs(
            id {audit_id},
            user_id INTEGER, username VARCHAR(100), action VARCHAR(100) NOT NULL,
            target_type VARCHAR(100), target_id VARCHAR(100), details TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""))
        c.execute(text("CREATE INDEX IF NOT EXISTS idx_records_province ON records(province)"))
        c.execute(text("CREATE INDEX IF NOT EXISTS idx_records_source_ne ON records(source_ne)"))
        c.execute(text("CREATE INDEX IF NOT EXISTS idx_records_dest_ne ON records(dest_ne)"))
        c.execute(text("CREATE INDEX IF NOT EXISTS idx_records_status ON records(status)"))
        c.execute(text("CREATE INDEX IF NOT EXISTS idx_records_service ON records(service)"))
        c.execute(text("CREATE INDEX IF NOT EXISTS idx_audit_created_at ON audit_logs(created_at)"))
        admin_user = os.getenv("INITIAL_ADMIN_USERNAME", "admin")
        admin_pass = os.getenv("INITIAL_ADMIN_PASSWORD")
        if not admin_pass and ENV != "production":
            admin_pass = "admin123"
        if admin_pass:
            exists = c.execute(text("SELECT id FROM users WHERE username=:u"), {"u": admin_user}).first()
            if not exists:
                c.execute(text("INSERT INTO users(username,password_hash,role) VALUES(:u,:p,'admin')"),
                          {"u": admin_user, "p": pwd.hash(admin_pass)})


init_db()


def current_user(request):
    return request.session.get("user")


def csrf_token(request):
    token = request.session.get("csrf_token")
    if not token:
        token = secrets.token_urlsafe(32)
        request.session["csrf_token"] = token
    return token


def check_csrf(request, token):
    return bool(token) and secrets.compare_digest(token, request.session.get("csrf_token", ""))


def redirect_login():
    return RedirectResponse("/login", 303)


def rows(sql="SELECT * FROM records ORDER BY id DESC", params=None):
    with db() as c:
        result = c.execute(text(sql), params or {}).mappings().all()
    return [dict(x) for x in result]


def log_action(request, action, target_type="", target_id="", details=""):
    u = current_user(request) or {}
    with db() as c:
        c.execute(text("""INSERT INTO audit_logs(user_id,username,action,target_type,target_id,details)
                        VALUES(:uid,:un,:a,:tt,:tid,:d)"""),
                  {"uid":u.get("id"), "un":u.get("username"), "a":action,
                   "tt":target_type, "tid":str(target_id) if target_id else "", "d":details})


def stats_for(rs):
    return {"total":len(rs), "used":sum(x.get("status")=="Used" for x in rs),
            "free":sum(x.get("status")=="Free" for x in rs), "reserved":sum(x.get("status")=="Reserved" for x in rs)}


def render_home(request, records=None, edit=None, message=None, error=None, page=1, pages=1):
    if not current_user(request): return redirect_login()
    if records is None:
        per_page = 50
        total = rows("SELECT COUNT(*) AS n FROM records")[0]["n"]
        pages = max(1, (total + per_page - 1)//per_page)
        page = max(1, min(page, pages))
        records = rows("SELECT * FROM records ORDER BY id DESC LIMIT :lim OFFSET :off", {"lim":per_page,"off":(page-1)*per_page})
    # Stats are global, not page-limited.
    all_rs = rows("SELECT status FROM records")
    return templates.TemplateResponse(request=request, name="index.html", context={"request":request,"records":records,"stats":stats_for(all_rs),
        "edit":edit,"message":message,"error":error,"page":page,"pages":pages,"csrf":csrf_token(request)})


