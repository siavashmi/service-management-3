    if not current_user(request): return redirect_login()
    df=pd.DataFrame(rows())
    if df.empty: return RedirectResponse("/?error=no_data",303)
    cols=["id"]+FIELDS
    out=BytesIO()
    with pd.ExcelWriter(out,engine="openpyxl") as w: df[cols].to_excel(w,index=False,sheet_name="Service Records")
    out.seek(0); log_action(request,"export","records",details=f"{len(df)} records")
    return StreamingResponse(out,media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        headers={"Content-Disposition":f'attachment; filename="service_usage_{datetime.now():%Y%m%d_%H%M%S}.xlsx"'})


