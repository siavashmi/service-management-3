@app.post("/save")
def save(request:Request, record_id:str=Form(""), province:str=Form("SHIRAZ"), type:str=Form("CORE"),
         source_ne:str=Form(""), source_port:str=Form(""), direction:str=Form("In"), dest_ne:str=Form(""),
         dest_port:str=Form(""), rate_type:str=Form("ODUCN"), rate_number:str=Form("1"), status:str=Form("Free"),
         service:str=Form(""), csrf:str=Form("")):
    u=current_user(request)
    if not u: return redirect_login()
    if not check_csrf(request,csrf): return RedirectResponse("/?error=csrf",303)
    if not all([source_ne.strip(),source_port.strip(),dest_ne.strip(),dest_port.strip()]): return RedirectResponse("/?error=required",303)
    values={"province":province.strip(),"type":type.strip(),"source_ne":source_ne.strip(),"source_port":source_port.strip(),
            "direction":direction.strip(),"dest_ne":dest_ne.strip(),"dest_port":dest_port.strip(),"rate_type":rate_type.strip(),
            "rate_number":str(rate_number).strip(),"status":status.strip(),"service":service.strip() or "N/A"}
    with db() as c:
        if record_id:
            rid=int(record_id)
            values["id"]=rid
            c.execute(text("""UPDATE records SET province=:province,type=:type,source_ne=:source_ne,source_port=:source_port,
                direction=:direction,dest_ne=:dest_ne,dest_port=:dest_port,rate_type=:rate_type,rate_number=:rate_number,
                status=:status,service=:service,updated_at=CURRENT_TIMESTAMP WHERE id=:id"""),values)
            action="update"
        else:
            res=c.execute(text("""INSERT INTO records(province,type,source_ne,source_port,direction,dest_ne,dest_port,rate_type,rate_number,status,service)
                VALUES(:province,:type,:source_ne,:source_port,:direction,:dest_ne,:dest_port,:rate_type,:rate_number,:status,:service)
                RETURNING id"""),values)
            rid=res.scalar_one()
            action="create"
    log_action(request,action,"record",rid)
    return RedirectResponse(f"/?success={'updated' if record_id else 'added'}",303)


